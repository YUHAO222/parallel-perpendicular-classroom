/* ---------- 模糊匹配：关键词加权 + 字符二元组 Dice（含 alias 变体） ---------- */
function ASK_NORM(s) {
  return String(s || '').toLowerCase()
    .replace(/[０-９]/g, c => String.fromCharCode(c.charCodeAt(0) - 0xFEE0))
    .replace(/∠|∟/g, '角')
    .replace(/∥/g, '平行').replace(/⊥/g, '垂直')
    .replace(/90\s*°|９０度/g, '90度')
    .replace(/[\s，。、？！：；""''（）()《》「」【】·,\.\?!:;"'~\-_/\\|]/g, '');
}
function ASK_BG(s) {
  const o = [];
  for (let i = 0; i < s.length - 1; i++) o.push(s.slice(i, i + 2));
  if (s.length === 1) o.push(s);
  return o;
}
function ASK_DICE(a, b) {
  if (!a.length || !b.length) return 0;
  const m = new Map();
  a.forEach(x => m.set(x, (m.get(x) || 0) + 1));
  let hit = 0;
  b.forEach(x => { const n = m.get(x) || 0; if (n > 0) { hit++; m.set(x, n - 1); } });
  return 2 * hit / (a.length + b.length);
}
var ASK_TH = 0.30;
var ASK_DEFQ = /什么|啥|定义|意思|叫|表示|符号|记/;
/* 返回 {entry, score} 或 null */
function ASK_MATCH(text, thr) {
  const u = ASK_NORM(text);
  if (u.length < 2) return null;
  const ub = ASK_BG(u), isDef = ASK_DEFQ.test(u);
  let best = null, bestS = 0;
  ASK_KB2.forEach(e => {
    let dq = ASK_DICE(ub, ASK_BG(ASK_NORM(e.q)));
    (e.alias || []).forEach(a => { const d = ASK_DICE(ub, ASK_BG(ASK_NORM(a))); if (d > dq) dq = d; });
    let hits = 0;
    e.kw.forEach(k => { if (u.indexOf(ASK_NORM(k)) >= 0) hits++; });
    const kwS = Math.min(1, hits / Math.min(3, e.kw.length));
    let s = 0.6 * kwS + 0.5 * dq + 0.2 * ASK_DICE(ub, ASK_BG(ASK_NORM(e.intent + e.kp)));
    if (isDef && /定义|概念|特征|本质|复习|关系/.test(e.intent)) s += 0.12;
    if (hits === 0 && dq < 0.5) s -= 0.25;
    if (s > bestS) { bestS = s; best = e; }
  });
  const T = thr == null ? ASK_TH : thr;
  return bestS >= T ? { entry: best, score: +bestS.toFixed(3) } : null;
}
